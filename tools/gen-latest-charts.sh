#!/usr/bin/env bash
# Write the registry.yaml of playbooks/files/latest-charts and
# examples/kind-nvsentinel/data: AICR's own registry entries
# for the charts we run newer than AICR pins, with only the version changed.
# An external entry replaces AICR's wholesale, so the whole entry is copied.
#   tools/gen-latest-charts.sh <aicr checkout at the tag in aicr_version>
set -euo pipefail
src=${1:?usage: gen-latest-charts.sh <aicr checkout>}/recipes/registry.yaml
out=$(dirname "$0")/../playbooks/files/latest-charts/registry.yaml
tag=$(git -C "$(dirname "$src")" describe --tags --exact-match)
nvsentinel=v1.30.0
cert_manager=v1.21.3
{
  echo "# Generated by tools/gen-latest-charts.sh from AICR $tag. Regenerate on an AICR bump."
  yq "(.components[] | select(.name == \"nvsentinel\") | .helm.defaultVersion) = \"$nvsentinel\"
    | (.components[] | select(.name == \"cert-manager\") | .helm.defaultVersion) = \"$cert_manager\"
    | .components |= map(select(.name == \"nvsentinel\" or .name == \"cert-manager\"))
    | ... comments=\"\"" "$src"
} > "$out"
cp "$out" "$(dirname "$0")/../examples/kind-nvsentinel/data/registry.yaml"
